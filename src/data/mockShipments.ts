const STORAGE_KEY = 'vanguard_logistics_shipments_v2';

export function getShipments(): Shipment[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed reading shipments from storage', e);
  }
  // Initialize with seed data
  saveAllShipments(INITIAL_SHIPMENTS);
  return INITIAL_SHIPMENTS;
}

export function saveAllShipments(shipments: Shipment[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(shipments));
  } catch (e) {
    console.error('Failed writing shipments to storage', e);
  }
}

export function addShipment(newShipment: Shipment): void {
  const current = getShipments();
  // Put newest at the front
  const updated = [newShipment, ...current.filter(s => s.trackingNumber !== newShipment.trackingNumber)];
  saveAllShipments(updated);
}

export function updateShipmentCheckpoint(trackingNumber: string, nextIndex: number): Shipment | null {
  const current = getShipments();
  const index = current.findIndex(s => s.trackingNumber.toUpperCase() === trackingNumber.toUpperCase());
  if (index === -1) return null;

  const shipment = { ...current[index] };
  const checkpoints = [...shipment.checkpoints];
  
  if (nextIndex >= 0 && nextIndex < checkpoints.length) {
    shipment.currentCheckpointIndex = nextIndex;
    shipment.status = checkpoints[nextIndex].status;

    // If reached delivered, create proof of delivery if not already present
    if (shipment.status === 'delivered' && !shipment.proofOfDelivery) {
      shipment.proofOfDelivery = {
        recipientName: shipment.recipient.name,
        deliveredAt: new Date().toISOString(),
        signatureSvg: 'M 10 40 Q 40 10 70 45 T 120 30 T 160 45',
        notes: `Received at ${shipment.recipient.city} destination premises.`,
      };
    }

    current[index] = shipment;
    saveAllShipments(current);
    return shipment;
  }
  return shipment;
}

export function findShipmentByQuery(query: string): Shipment | undefined {
  const clean = query.trim().toUpperCase();
  if (!clean) return undefined;
  const list = getShipments();
  return list.find(s => 
    s.trackingNumber.toUpperCase() === clean ||
    s.referenceNumber.toUpperCase() === clean ||
    (s.telemetry?.vehicleId && s.telemetry.vehicleId.toUpperCase() === clean) ||
    (s.telemetry?.vehicleId && s.telemetry.vehicleId.toUpperCase().includes(clean)) ||
    (clean.includes('774') || clean.includes('AERO') || clean.includes('938102941') ? s.id === 'shp-002' : false) ||
    s.trackingNumber.replace(/[^A-Z0-9]/g, '').includes(clean.replace(/[^A-Z0-9]/g, '')) ||
    s.recipient.name.toUpperCase().includes(clean) ||
    s.shipper.city.toUpperCase().includes(clean) ||
    s.recipient.city.toUpperCase().includes(clean)
  );
}
